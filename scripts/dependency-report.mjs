#!/usr/bin/env node
/**
 * Turn `npm outdated --json` into a Markdown report.
 *
 * Used by the scheduled `dependency-check` GitLab CI job to keep a single
 * issue up to date with the dependency updates that are available.
 *
 * Usage: node scripts/dependency-report.mjs [outdated.json]
 *
 * Writes the report to stdout. Exits 0 when there is nothing actionable and
 * 1 when there is, so the CI job can decide whether to open or update an
 * issue.
 */

/**
 * Updates that must not be applied yet, with the reason.
 *
 * The TypeScript 7 guard is the important one: typescript-eslint@8 peers
 * `typescript: ">=4.8.4 <6.1.0"` and hard-throws on TS 7, which takes the
 * whole lint step down with it. TypeScript 7.0.x is npm's `latest`, so a
 * naive upgrade would break the build. Revisit this when typescript-eslint
 * ships support for TS 7.1 (tracked upstream).
 */
const BLOCKED = {
  typescript:
    "TypeScript 7 breaks ESLint: typescript-eslint peers `typescript: >=4.8.4 <6.1.0` " +
    "and hard-throws on TS 7, which takes the lint step down. Revisit when " +
    "typescript-eslint ships support for TS 7.1.",
};

async function readJson(path) {
  try {
    const { readFile } = await import("node:fs/promises");
    const raw = await readFile(path, "utf-8");
    if (!raw.trim()) return {};
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

function main() {
  const path = process.argv[2] ?? "outdated.json";
  return readJson(path).then((outdated) => {
    const entries = Object.entries(outdated ?? {});

    const actionable = [];
    const blocked = [];

    for (const [name, info] of entries) {
      const current = info.current ?? "?";
      const wanted = info.wanted ?? "?";
      const latest = info.latest ?? "?";
      const reason = BLOCKED[name];

      if (reason) {
        blocked.push({ name, current, wanted, latest, reason });
      } else {
        actionable.push({ name, current, wanted, latest });
      }
    }

    const lines = [];
    lines.push("## Dependency updates available");
    lines.push("");
    lines.push(`_Generated by the scheduled \`dependency-check\` CI job._`);
    lines.push("");

    if (actionable.length === 0 && blocked.length === 0) {
      lines.push("Everything is up to date. No action needed.");
    } else {
      if (actionable.length > 0) {
        lines.push("### Actionable");
        lines.push("");
        lines.push("| Package | Current | Wanted | Latest |");
        lines.push("|---|---|---|---|");
        for (const e of actionable) {
          lines.push(`| \`${e.name}\` | ${e.current} | ${e.wanted} | ${e.latest} |`);
        }
        lines.push("");
      }

      if (blocked.length > 0) {
        lines.push("### Blocked on purpose");
        lines.push("");
        lines.push("These have a newer release available but must not be taken yet:");
        lines.push("");
        for (const e of blocked) {
          lines.push(`- **\`${e.name}\`** — current ${e.current}, latest ${e.latest}`);
          lines.push(`  - ${e.reason}`);
        }
        lines.push("");
      }
    }

    process.stdout.write(lines.join("\n") + "\n");
    process.exitCode = actionable.length > 0 ? 1 : 0;
  });
}

main();
